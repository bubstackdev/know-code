def read_jsonl(p):
    p = Path(p)
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()] if p.exists() else []


def write_jsonl(p, rows):
    with open(p, "w") as f:
        for r in rows:
            f.write(json.dumps(r, sort_keys=True) + "\n")


def ticket_questions(cands, stories):
    """Ticket locate questions: each candidate change whose story title (stories: {id: title or None}) is usable.
    Returns (questions, labels, skipped story ids with the reason)."""
    qs, ls, skipped_ = [], [], []
    for t in cands:
        raw = stories.get(str(t["story"]))
        title = usable_title(raw) if raw else None
        if not title:
            skipped_.append((t["story"], "story not found" if not raw else "title too thin"))
            continue
        q, lab = json.loads(json.dumps(t["question"])), json.loads(json.dumps(t["label"]))
        qid = f"B-locate-{len(qs) + 1:03d}"
        q["id"] = lab["id"] = qid
        q["question"] = f"In {q['repos'][0]}, where is this handled: \"{title}\"? List the source files involved."
        q["meta"] = {"title_source": "story title", "story": t["story"]}
        qs.append(q)
        ls.append(lab)
    return qs, ls, skipped_


def assemble(a):
    """Joins history questions, ticket questions (titles from stories.json, {story id: title or null}, looked up by
    hand in the ticket tracker) and the structural questions with a hand label in label-parts/*.jsonl. Structural
    candidates without a label (unused spares, or drops listed in label-parts/*-dropped.jsonl) are left out. Writes
    questions.jsonl, labels.jsonl and manifest.md."""
    out = Path(a.out)
    qs = read_jsonl(out / "history-questions.jsonl")
    ls = read_jsonl(out / "history-labels.jsonl")
    stories = json.loads((out / "stories.json").read_text()) if (out / "stories.json").exists() else {}
    tq, tl, tskip = ticket_questions(read_jsonl(out / "ticket-candidates.jsonl"), stories)
    qs += tq
    ls += tl
    hand, dropped = {}, []
    for p in sorted((out / "label-parts").glob("*.jsonl")):
        rows = read_jsonl(p)
        if p.stem.endswith("-dropped"):
            dropped += rows
        else:
            hand.update({lab["id"]: lab for lab in rows})
    cands = read_jsonl(out / "structural-candidates.jsonl")
    for q in cands:
        if q["id"] in hand:
            qs.append(q)
            ls.append(hand[q["id"]])
    # Questions stay in the files but out of scoring when excluded: about a compared tool's own source
    # (population.json `tool_repos`), or listed with a reason in exclusions.json ({id: reason}).
    pop_cfg = json.loads((out / "population.json").read_text()) if (out / "population.json").exists() else {}
    tool_repos = set(pop_cfg.get("tool_repos", []))
    reasons = json.loads((out / "exclusions.json").read_text()) if (out / "exclusions.json").exists() else {}
    labs = {x["id"]: x for x in ls}
    for q in qs:
        why = reasons.get(q["id"])
        if not why and tool_repos & set(q["repos"]):
            why = "subject is in a compared tool's own repo"
        if why and q["id"] in labs:
            q["excluded"] = labs[q["id"]]["excluded"] = True
            q["excluded_reason"] = labs[q["id"]]["excluded_reason"] = why
    errs = validate_bank(qs, ls)
    for e in errs:
        print("  " + e)
    write_jsonl(out / "questions.jsonl", qs)
    write_jsonl(out / "labels.jsonl", ls)
    (out / "manifest.md").write_text(manifest(out, qs, ls, tskip, dropped, cands))
    by = Counter(q["stratum"] for q in qs if not q.get("excluded"))
    comp = Counter(lab["completeness"] for lab in ls if not lab.get("excluded"))
    print(f"{sum(by.values())} scored questions ({len(qs)} with excluded); "
          + ", ".join(f"{k} {v}" for k, v in sorted(by.items())))
    print("labels: " + ", ".join(f"{k} {v}" for k, v in sorted(comp.items())))
    return 1 if errs else 0


