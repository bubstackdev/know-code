ACTIVE_SINCE = "2025-09-09"  # 400 days before UNTIL: the history every clone keeps


def active_files(d, since=ACTIVE_SINCE, until=UNTIL):
    """Paths a person (not a bot) changed in the window. A shallow clone's boundary commit has no parent here and
    would list every file as added, so commits without a parent are skipped; so are merges (their changes are in
    the merged commits)."""
    log = git(d, "log", f"--since={since}", f"--until={until}", "--no-merges", "--name-only",
              "--format=%x01%P%x00%an%x00%ae")
    out = set()
    for rec in log.split("\x01")[1:]:
        head, _, body = rec.partition("\n")
        parents, name, email = (head.split("\x00") + ["", ""])[:3]
        if not parents.strip() or is_bot(name, email):
            continue
        out.update(x for x in body.split("\n") if x.strip())
    return out


def cluster_key(stratum, by_key):
    """What makes two subjects correlated samples: the repo of the subject's (primary) declaration. One question
    per repo per stratum and set; for Terraform that also caps root configurations, which share a repo."""
    def key(k):
        return by_key[k][0]["repo"]
    return key


def capped_sample(seed, keys, want, cluster):
    """`want` keys drawn at random with at most one per cluster. Draws `random.Random(seed).sample(keys, m)` for a
    growing m and keeps the first key of each cluster in draw order; when the first draw has no two keys in one
    cluster this returns exactly that draw, so adding the cap leaves uncapped draws unchanged."""
    m = min(want, len(keys))
    while True:
        drawn = random.Random(seed).sample(keys, m)
        out, seen = [], set()
        for k in drawn:
            if cluster(k) not in seen:
                seen.add(cluster(k))
                out.append(k)
        if len(out) >= want or m >= len(keys):
            return out[:want]
        m = min(len(keys), m * 2)


def family_note(cands):
    names = sorted({c["name"] for c in cands if "name" in c})
    if len(names) < 2:
        return ""
    return f", one of {len(names)} sharded tables named {cands[0].get('family', cands[0]['key'])}_*,"


def structural(a):
    root, out = Path(a.root), Path(a.out)
    seen = Seen(a.seen)
    census_ = json.loads((out / "census.json").read_text())
    weights = census_["weights"]
    alloc = allocate(weights, a.n, minimum=a.min_per_stratum)
    rows, pops, ctx = [], {}, {}
    repos = repos_under(root)
    excluded = census_.get("excluded_repos", {})
    repos = [d for d in repos if d.name not in excluded]
    listing, active = {}, {}
    for d in repos:
        files = tracked(d)
        listing[d.name] = (files, is_ansible_repo(files), is_angular_repo(files))
        active[d.name] = active_files(d)
    for stratum in sorted(alloc):
        cands = []
        for d in repos:
            files, ans, ang = listing[d.name]
            for c in structural_candidates(d, files, stratum, ans, ang):
                c["repo"] = d.name
                cands.append(c)
        cands.sort(key=lambda c: (c["repo"], c["file"], c["line"], c["key"]))
        # uniform over distinct subjects, so a name declared in many places is not drawn more often
        by_key = defaultdict(list)
        unit = (lambda c: c["key"]) if stratum in {"sql-table-access", "bus-pub-sub"} else \
            (lambda c: (c["repo"], c["key"], c["file"]))
        for c in cands:
            by_key[unit(c)].append(c)
        for k in by_key:  # the primary declaration first: a live schema before a replica copy
            by_key[k].sort(key=lambda c: (c.get("replica", False), c["repo"], c["file"], c["line"]))
        n_all = len(by_key)
        by_key = {k: v for k, v in by_key.items() if not seen.subject(stratum, v)}
        keys = sorted(by_key, key=str)
        live = [k for k in keys if any(c["file"] in active[c["repo"]] for c in by_key[k])]
        pops[stratum] = {"candidates": len(cands), "subjects": len(keys), "active_subjects": len(live),
                         "seen_excluded": n_all - len(keys)}
        # one RNG per stratum and subset, so fixing one stratum's population never moves another stratum's draw
        cluster = cluster_key(stratum, by_key)
        picks = capped_sample(f"{a.seed}/{stratum}", keys, alloc[stratum] + a.spare, cluster)
        apicks = capped_sample(f"{a.seed}/{stratum}/active", live, alloc[stratum] + a.spare, cluster)

        def row(k, qid, spare, subset):
            c = by_key[k][0]
            qtype, kind, text = QUESTION_TEXT[stratum]
            head = census_["heads"][c["repo"]]
            return {"id": qid, "stratum": stratum, "source": "structural",
                    "type": qtype, "question": text.format(repo=c["repo"], name=c.get("name", c["key"]),
                                                           family=family_note(by_key[k]), **{
                        k2: v for k2, v in c.items() if k2 not in {"repo", "name", "family"}}),
                    "repos": [c["repo"]], "commit": {c["repo"]: head}, "index_state": {c["repo"]: head},
                    "answer_kind": kind,
                    "meta": {"subject": c["key"], "at": f"{c['repo']}/{c['file']}:{c['line']}",
                             "spare": spare, "declared_in": len(by_key[k]), "subset": subset}}

        for i, k in enumerate(apicks):
            rows.append(row(k, f"C-{stratum}-a{i + 1:03d}", i >= alloc[stratum], "active"))
        for i, k in enumerate(picks):
            rows.append(row(k, f"C-{stratum}-u{i + 1:03d}", i >= alloc[stratum], "uniform"))
        if stratum in COMPLEX and a.complex:
            # A second, separate draw (its own RNG, so the natural draw above is unchanged) restricted to harder
            # subjects (see the filter functions); reported as its own "hard" subset, never mixed into the headline.
            crng = random.Random(f"{a.seed}/{stratum}/hard")
            decls = Counter((c["repo"], c["key"]) for c in cands)
            for k in keys:
                by_key[k][0]["overloads"] = len(by_key[k])
            n_hard = COMPLEX_N.get(stratum, a.complex)
            # test the shuffled subjects in order until enough pass, so the filter runs on few of them
            order = crng.sample(keys, len(keys))
            hard, taken = [], set()
            for k in order:
                if len(hard) >= n_hard + a.spare:
                    break
                if cluster(k) not in taken and COMPLEX[stratum](by_key[k][0], root, ctx, decls):
                    hard.append(k)
                    taken.add(cluster(k))
            for i, k in enumerate(hard):
                rows.append(row(k, f"C-{stratum}-x{i + 1:03d}", i >= n_hard, "hard"))
    write_jsonl(out / "structural-candidates.jsonl", rows)
    (out / "structural-stats.json").write_text(json.dumps({"seed": a.seed, "allocation": alloc, "population": pops,
                                                           "complex_per_stratum": a.complex,
                                                           "min_per_stratum": a.min_per_stratum},
                                                          indent=1, sort_keys=True))
    for s in sorted(alloc):
        print(f"  {s:20} {alloc[s]:3} of {pops[s]['subjects']} subjects ({pops[s]['candidates']} candidates)")


