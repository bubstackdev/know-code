BOT = re.compile(r"\bbot\b|\[bot\]|jenkins|renovate|dependabot|semantic-release|gitlab_token|\bci\b|"
                 r"noreply@gitlab|project_\d+_bot", re.I)
NON_MR_MERGE = re.compile(r"^Merge (remote-tracking branch|branch '[^']+' of |branch '(master|main|develop)' into)",
                          re.I)
MR_LINE = re.compile(r"^See merge request\s+(\S+)", re.M)
STORY = re.compile(r"\bsc[-_]?(\d{4,7})\b", re.I)
BRANCH = re.compile(r"^Merge branch '([^']+)' into '([^']+)'")
GENERIC = re.compile(r"^(wip|update\b.*\.\w+$|updated?|fix|fixes|changes|minor|merge|test|tmp|temp|cleanup|"
                     r"initial commit|version|bump|release|readme)\b", re.I)


def is_bot(name, email):
    return bool(BOT.search(name) or BOT.search(email))


def changes(d, since=SINCE, until=UNTIL):
    """First-parent changes on the default branch in the window: merge requests (diffed against the first parent) and
    direct commits. Each row: sha, parent, time, author, subject, body, files [(status, path, old)]."""
    log = git(d, "log", "--first-parent", f"--since={since}", f"--until={until}",
              "--format=%x01%H%x00%P%x00%ct%x00%an%x00%ae%x00%B")
    rows = []
    for rec in log.split("\x01")[1:]:
        sha, parents, ct, an, ae, body = rec.split("\x00", 5)
        parents = parents.split()
        if not parents:
            continue
        rows.append({"sha": sha, "parent": parents[0], "merge": len(parents) > 1,
                     "second": parents[1] if len(parents) > 1 else None, "time": int(ct), "author": an, "email": ae,
                     "body": body.strip()})
    return rows


def changed_files(d, parent, sha):
    out = git(d, "diff", "--name-status", "-M", parent, sha)
    files = []
    for line in out.splitlines():
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        st = parts[0][:1]
        if st == "R" and len(parts) == 3:
            files.append({"status": "R", "path": parts[2], "old": parts[1]})
        else:
            files.append({"status": st, "path": parts[1]})
    return files


def mr_title(c):
    """The human title of a change: a merge request's title (GitLab writes it after the merge line) or the commit
    subject."""
    lines = [ln.strip() for ln in c["body"].splitlines()]
    subject = lines[0] if lines else ""
    if c["merge"]:
        rest = [ln for ln in lines[1:] if ln and not MR_LINE.match(ln) and not ln.startswith(("Closes ", "Related to"))]
        if rest:
            return rest[0]
    return subject


def merge_authors(d, c):
    if not c["merge"]:
        return [(c["author"], c["email"])]
    out = git(d, "log", "--format=%an%x00%ae", f"{c['parent']}..{c['second']}")
    return [tuple(x.split("\x00", 1)) for x in out.splitlines() if "\x00" in x] or [(c["author"], c["email"])]


def exclusion(d, c, files):
    """Why a change is left out, or None. Order matters only for the counts in the manifest."""
    subject = c["body"].splitlines()[0] if c["body"] else ""
    if c["merge"] and NON_MR_MERGE.match(subject):
        return "merge of a branch, not a merge request"
    if not files:
        return "no diff"
    if len(files) > MAX_FILES:
        return "bulk (>30 files)"
    if all(LOCKFILES.search(f["path"]) for f in files):
        return "lockfile only"
    if all(is_bot(n, e) for n, e in merge_authors(d, c)):
        return "bot"
    code = [f for f in files if os.path.splitext(f["path"])[1].lower() in CODE_EXTS or CI_NAMES.search(f["path"])]
    if not code:
        return "no code files"
    paths = sorted({p for f in files for p in (f["path"], f.get("old")) if p})
    if not git(d, "diff", "-w", "--ignore-blank-lines", "--no-renames", "--stat", c["parent"], c["sha"], "--",
               *paths).strip():
        return "formatting only"
    if all(f["status"] == "R" for f in files) and not git(d, "diff", "-M100%", "--stat", c["parent"], c["sha"]).strip():
        return "pure rename"
    return None


def parent_in_clone(d, sha):
    """Whether a commit is present in the clone with its tree (a shallow clone's history ends somewhere)."""
    out = subprocess.run(["git", "-C", str(d), "cat-file", "-e", f"{sha}^{{tree}}"], capture_output=True)
    return out.returncode == 0


def existing_at(d, sha, paths):
    """The subset of paths that exist in the tree at sha."""
    if not paths:
        return set()
    out = git(d, "ls-tree", "-r", "--name-only", sha)
    have = set(out.splitlines())
    return {p for p in paths if p in have}


# Configuration a change may touch as part of its concept (settings, app config, deploy variables).
CONFIG_EXTS = {".json", ".config", ".xml", ".toml", ".ini", ".properties", ".conf", ".env", ".hcl", ".tfvars", ".ps1",
               ".psm1", ".bat", ".cmd"}


def is_code(path):
    ext = os.path.splitext(path)[1].lower()
    code = ext in CODE_EXTS or ext in CONFIG_EXTS or bool(CI_NAMES.search(path))
    return code and not LOCKFILES.search(path)


# Declarations and calls, for impact questions. C#, TypeScript and CFML script syntax share the shapes used here.
DECL = re.compile(r"^\s*(?:(?:public|private|protected|internal|static|virtual|override|async|sealed|abstract|"
                  r"export|readonly)\s+)+(?:[\w<>\[\],.?]+\s+)?(\w+)\s*(?:<[^>()]*>)?\s*\(([^)]*)\)?")
CF_DECL = re.compile(r"<cffunction\s+[^>]*name\s*=\s*[\"'](\w+)[\"']|^\s*(?:public|private|remote|package)?\s*"
                     r"(?:\w+\s+)?function\s+(\w+)\s*\(", re.I)
KEYWORDS = {"if", "for", "foreach", "while", "switch", "catch", "using", "lock", "return", "new", "typeof", "nameof",
            "sizeof", "base", "this", "get", "set", "constructor", "function", "when", "default"}


def hunks(d, parent, sha, path, old=None):
    """Removed and added lines of one file's diff with their line numbers on each side: [(sign, line_no, text)]."""
    args = ["diff", "-U0", "--no-color", parent, sha, "--"]
    args += [old, path] if old and old != path else [path]
    out = git(d, *args)
    rows, ol, nl = [], 0, 0
    for line in out.splitlines():
        if line.startswith("@@"):
            m = re.match(r"@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@", line)
            ol, nl = int(m.group(1)), int(m.group(2))
        elif line.startswith("-") and not line.startswith("---"):
            rows.append(("-", ol, line[1:]))
            ol += 1
        elif line.startswith("+") and not line.startswith("+++"):
            rows.append(("+", nl, line[1:]))
            nl += 1
    return rows


TYPE_DECL = re.compile(r"\b(class|record|struct|interface|enum|delegate|event)\b")


def decl_name(text):
    m = DECL.match(text)
    if m and m.group(1) not in KEYWORDS and not TYPE_DECL.search(text[:m.start(1)]):
        return m.group(1), (m.group(2) or "").strip()
    m = CF_DECL.search(text)
    if m:
        return (m.group(1) or m.group(2)), ""
    return None


def impact_candidates(diffs):
    """Signature changes and renames in one change, with the call sites the same change updated.

    `diffs` maps path -> hunks (see `hunks`). A removed declaration of `name` paired with an added declaration of
    `name` with other parameters is a signature change; one paired with an added declaration of a different name
    at the same position (the next added line in the file) is a rename. Call sites are removed lines elsewhere that
    call the old name and are not declarations. Returns [{name, new_name, file, line, sites: [(path, line)]}]."""
    out = []
    for path, rows in sorted(diffs.items()):
        removed = [(n, t) for s, n, t in rows if s == "-"]
        added = [(n, t) for s, n, t in rows if s == "+"]
        added_decls = [(n, decl_name(t)) for n, t in added]
        added_decls = [(n, x) for n, x in added_decls if x]
        for n, t in removed:
            dn = decl_name(t)
            if not dn:
                continue
            name, params = dn
            same = [x for _, x in added_decls if x[0] == name]
            if same:
                if any(p == params for _, p in same):
                    continue
                new_name = name
            else:
                # a rename: the first added declaration that is not the name of any removed one
                removed_names = {decl_name(tt)[0] for _, tt in removed if decl_name(tt)}
                fresh = [x for _, x in added_decls if x[0] not in removed_names]
                if not fresh:
                    continue
                new_name = fresh[0][0]
            call = re.compile(rf"(?<![\w$])(?:\.|\b){re.escape(name)}\s*(?:<[^>()]*>)?\s*\(")
            sites = []
            for p2, rows2 in sorted(diffs.items()):
                for s2, n2, t2 in rows2:
                    if s2 != "-" or (p2 == path and n2 == n) or decl_name(t2):
                        continue
                    if call.search(t2) and not t2.lstrip().startswith(("//", "*", "/*", "<!---")):
                        sites.append((p2, n2))
            if sites:
                out.append({"name": name, "new_name": new_name, "file": path, "line": n, "sites": sites})
    return out


class Seen:
    """Subjects already seen during development (a private JSONL of {kind, repo, value}; see the manifest), which a
    draw leaves out. Kinds: symbol (repo or "*", name), file (repo, path), repo (repo, "deploy"), commit and parent
    (repo, sha), story ("*", id)."""

    def __init__(self, path=None):
        self.keys = set()
        if path and Path(path).exists():
            for r in read_jsonl(path):
                self.keys.add((r["kind"], r["repo"], str(r["value"])))
        self.hits = Counter()

    def has(self, kind, repo, value, what):
        hit = (kind, repo, str(value)) in self.keys or (kind, "*", str(value)) in self.keys
        if hit:
            self.hits[what] += 1
        return hit

    def subject(self, stratum, cands):
        """Whether a structural subject (all its declarations) was seen."""
        for c in cands:
            names = {str(c["key"]), str(c.get("name", "")), str(c.get("family", ""))} - {""}
            if (any(self.has("symbol", c["repo"], n, stratum) for n in names)
                    or self.has("file", c["repo"], c["file"], stratum)
                    or (stratum == "deploy-chain" and self.has("repo", c["repo"], "deploy", stratum))):
                return True
        return False


def at_head(d, path):
    """The file's text at HEAD, or None when it does not exist there."""
    out = subprocess.run(["git", "-C", str(d), "show", f"HEAD:{path}"], capture_output=True, text=True,
                         errors="replace")
    return out.stdout if out.returncode == 0 else None


def history(a):
    root, out = Path(a.root), Path(a.out)
    seen = Seen(a.seen)
    out.mkdir(parents=True, exist_ok=True)
    census_ = json.loads((out / "census.json").read_text())
    lang = census_["repo_language"]
    why, pool, tickets = Counter(), defaultdict(list), []
    cached = out / "history-pool.jsonl"
    if cached.exists() and not a.remine:
        mined = read_jsonl(cached)
        why.update(json.loads((out / "history-stats.json").read_text())["mined"])
    else:
        mined = []
        for d in repos_under(root):
            for c in changes(d):
                files = changed_files(d, c["parent"], c["sha"])
                w = exclusion(d, c, files)
                if w:
                    why[w] += 1
                    continue
                row = {"repo": d.name, "sha": c["sha"], "parent": c["parent"], "time": c["time"],
                       "merge": c["merge"], "title": mr_title(c), "subject": c["body"].splitlines()[0],
                       "files": files, "language": lang.get(d.name, "none")}
                m = BRANCH.match(row["subject"])
                sm = STORY.search(m.group(1) if m else row["subject"])
                if sm:
                    row["story"] = int(sm.group(1))
                mined.append(row)
                why["eligible"] += 1
        write_jsonl(cached, mined)
    mined_why = dict(why)
    excluded = census_.get("excluded_repos", {})
    for row in mined:
        if row["repo"] in excluded:
            why["outside population (mirror or non-production repo)"] += 1
            continue
        pool[row["language"]].append(row)
    rng = random.Random(a.seed)
    langs = sorted(pool)
    counts = {k: len(pool[k]) for k in langs}
    plan = {"locate": a.locate, "co-change": a.cochange, "impact": a.impact}
    questions, labels, used = [], [], set()

    def draw(kind, n, make):
        big = {k: counts[k] for k in langs if counts[k] >= 5}
        alloc = allocate(big, n, minimum=1 if n >= len(big) else 0)
        made = 0

        def take(cands, quota):
            nonlocal made
            got = 0
            for r in cands:
                if got >= quota:
                    break
                if (r["repo"], r["sha"]) in used:
                    continue
                if (seen.has("commit", r["repo"], r["sha"], "history") or seen.has("parent", r["repo"], r["parent"],
                                                                                    "history")
                        or ("story" in r and seen.has("story", "*", r["story"], "history"))):
                    continue
                if not parent_in_clone(root / r["repo"], r["parent"]):
                    why["parent not in the clone"] += 1
                    continue
                qa = make(r, f"A-{kind}-{made + 1:03d}")
                if qa:
                    used.add((r["repo"], r["sha"]))
                    qa[0]["meta"]["language"] = r["language"]
                    questions.append(qa[0])
                    labels.append(qa[1])
                    made += 1
                    got += 1

        for lng in sorted(alloc):
            cands = sorted(pool[lng], key=lambda r: (r["repo"], r["sha"]))
            rng.shuffle(cands)
            take(cands, alloc[lng])
        if made < n:  # a language without enough answerable changes: top up from the whole pool
            short[kind] = n - made
            cands = sorted((r for rs in pool.values() for r in rs), key=lambda r: (r["repo"], r["sha"]))
            rng.shuffle(cands)
            take(cands, n - made)
        why[f"drawn {kind}"] = made

    short = {}

    def counted(kind, fn):
        def make(r, i):
            res = fn(r, i)
            if isinstance(res, str):  # a reason the change gave no question
                why[f"skipped {kind}: {res}"] += 1
                return None
            return res
        return make

    draw("locate", plan["locate"], counted("locate", lambda r, i: locate_question(root / r["repo"], r, i, "history")))
    draw("co-change", plan["co-change"],
         counted("co-change", lambda r, i: cochange_question(root / r["repo"], r, i, rng, seen)))
    draw("impact", plan["impact"], counted("impact", lambda r, i: impact_question(root / r["repo"], r, i)))

    # ticket candidates: changes whose branch names a story; titles are looked up afterwards (see manifest)
    linked = sorted((r for rs in pool.values() for r in rs if "story" in r and (r["repo"], r["sha"]) not in used),
                    key=lambda r: (r["repo"], r["sha"]))
    rng.shuffle(linked)
    seen_story = set()
    for r in linked:
        if len(tickets) >= a.tickets or r["story"] in seen_story:
            continue
        if (seen.has("story", "*", r["story"], "ticket") or seen.has("commit", r["repo"], r["sha"], "ticket")
                or not parent_in_clone(root / r["repo"], r["parent"])):
            continue
        qa = locate_question(root / r["repo"], r, "B-locate-000", "ticket")
        if isinstance(qa, str):
            why[f"skipped ticket: {qa}"] += 1
            qa = None
        if qa:
            seen_story.add(r["story"])
            tickets.append({"story": r["story"], "question": qa[0], "label": qa[1]})
    write_jsonl(out / "history-questions.jsonl", questions)
    write_jsonl(out / "history-labels.jsonl", labels)
    write_jsonl(out / "ticket-candidates.jsonl", tickets)
    stats = {"mined": mined_why, "why": dict(why), "topped_up": short, "eligible_by_language": counts,
             "linked_to_story": sum(1 for rs in pool.values() for r in rs if "story" in r),
             "seed": a.seed, "since": SINCE, "until": UNTIL, "seen_excluded": dict(seen.hits)}
    (out / "history-stats.json").write_text(json.dumps(stats, indent=1, sort_keys=True))
    print(json.dumps(stats, indent=1, sort_keys=True))


def split_truth(d, r, paths):
    """Code paths that existed at the parent and still exist at HEAD (both tools index HEAD), split into source and
    tests; plus the ones left out (added by the change, or gone since)."""
    have = existing_at(d, r["parent"], paths) & existing_at(d, "HEAD", paths)
    src = sorted(p for p in have if not is_test_path(p))
    tests = sorted(p for p in have if is_test_path(p))
    return src, tests, sorted(set(paths) - have)


def item(repo, path, evidence):
    return {"item": f"{repo}/{path}", "evidence": evidence}


def base_question(r, qid, stratum, source, qtype, text, kind="files", repos=None):
    repos = repos or [r["repo"]]
    return {"id": qid, "stratum": stratum, "source": source, "type": qtype, "question": text, "repos": repos,
            "commit": {r["repo"]: r["parent"]}, "index_state": {r["repo"]: r["parent"]}, "answer_kind": kind,
            "meta": {}}


def locate_question(d, r, qid, source):
    title = usable_title(r["title"])
    if not title:
        return None
    # generated and vendored files (bundles, lockfiles' kin) are not where a concept is handled
    code = ([f["path"] for f in r["files"] if is_code(f["path"]) and not skipped(f["path"])]
            + [f["old"] for f in r["files"] if f.get("old") and not skipped(f["old"])])
    src, tests, added = split_truth(d, r, code)
    if not src:
        return "no changed source file left at HEAD"
    stratum = "ticket-locate" if source == "ticket" else "history-locate"
    q = base_question(r, qid, stratum, source, "locate",
                      f"In {r['repo']}, where is this handled: \"{title}\"? List the source files involved.")
    q["meta"] = {"title_source": "story title" if source == "ticket" else ("merge request title" if r["merge"]
                                                                            else "commit subject")}
    ev = f"git diff {r['parent'][:12]}..{r['sha'][:12]}"
    lab = {"id": qid, "items": [item(r["repo"], p, ev) for p in src], "tests": [item(r["repo"], p, ev) for p in tests],
           "completeness": "exhaustive", "match": "file",
           "note": f"Files the change touched that existed at its parent and still exist at HEAD; {len(added)} "
                   f"left out (added by the change, or gone at HEAD): {added[:5]}. Truth is the change, so a file "
                   f"that handles the concept but did not change counts as a false positive.",
           "change": {"repo": r["repo"], "sha": r["sha"], "parent": r["parent"], "title": r["title"]}}
    return q, lab


def cochange_question(d, r, qid, rng, seen=None):
    code = sorted({f["path"] for f in r["files"]
                   if is_code(f["path"]) and not skipped(f["path"]) and f["status"] != "A"})
    src, tests, _ = split_truth(d, r, code)
    if not src or len(src) + len(tests) < 2:
        return "fewer than two changed files left at HEAD"
    f = rng.choice(src)
    if seen and seen.has("file", r["repo"], f, "history"):
        return "input file seen in development"
    others = [p for p in src if p != f]
    if not others and not tests:
        return None
    q = base_question(r, qid, "history-co-change", "history", "co-change",
                      f"In {r['repo']}, if I change {f}, what other files usually need to change with it?")
    q["meta"] = {"input_file": f"{r['repo']}/{f}", "history_until": r["parent"]}
    ev = f"git diff {r['parent'][:12]}..{r['sha'][:12]}"
    lab = {"id": qid, "items": [item(r["repo"], p, ev) for p in others],
           "tests": [item(r["repo"], p, ev) for p in tests], "completeness": "exhaustive", "match": "file",
           "note": "The other files this one change touched (existing at its parent). One commit is a noisy oracle "
                   "for 'usually': score recall first; precision against a single change undercounts.",
           "change": {"repo": r["repo"], "sha": r["sha"], "parent": r["parent"], "title": r["title"]}}
    if not others:
        return None
    return q, lab


def impact_question(d, r, qid):
    exts = {".cs", ".ts", ".tsx", ".js", ".cfc", ".cfm"}
    diffs = {}
    for f in r["files"]:
        if os.path.splitext(f["path"])[1].lower() in exts and f["status"] in "MR" and not skipped(f["path"]):
            diffs[f.get("old") or f["path"]] = hunks(d, r["parent"], r["sha"], f["path"], f.get("old"))
    cands = impact_candidates(diffs)
    if not cands:
        return "no signature change with updated call sites"
    c = cands[0]
    what = "renamed" if c["new_name"] != c["name"] else "changed signature"
    # Both tools index HEAD, so the question names the symbol as it is there: the new name, in the file's current
    # path. A symbol gone or renamed again since the change gives no question; call-site files must still call it.
    moved = {f.get("old"): f["path"] for f in r["files"] if f.get("old")}
    decl_file = moved.get(c["file"], c["file"])
    text = at_head(d, decl_file)
    decl = None
    if text is not None:
        for n, line in enumerate(text.splitlines(), 1):
            dn = decl_name(line)
            if dn and dn[0] == c["new_name"]:
                decl = n
                break
    if decl is None:
        return "symbol gone or renamed at HEAD"
    call = re.compile(rf"(?<![\w$])(?:\.|\b){re.escape(c['new_name'])}\s*(?:<[^>()]*>)?\s*\(")
    files = []
    for p in sorted({moved.get(p, p) for p, _ in c["sites"]}):
        t = text if p == decl_file else at_head(d, p)
        if t is None:
            continue
        lines = [n for n, line in enumerate(t.splitlines(), 1) if call.search(line) and not decl_name(line)]
        if lines:
            files.append((p, lines))
    if not files:
        return "no updated call site still calls it at HEAD"
    q = base_question(r, qid, "history-impact", "history", "impact",
                      f"In {r['repo']}, what calls {c['new_name']} (declared at {decl_file}:{decl})?")
    head = git(d, "rev-parse", "HEAD").strip()
    q["commit"] = {r["repo"]: head}
    q["index_state"] = {r["repo"]: head}
    q["meta"] = {"symbol": c["new_name"], "declared_at": f"{r['repo']}/{decl_file}:{decl}", "was": c["name"]}
    ev = f"call sites updated by {r['sha'][:12]}; at HEAD lines {{lines}}"
    items = [{"item": f"{r['repo']}/{p}", "evidence": ev.format(lines=ls[:5])} for p, ls in files
             if not is_test_path(p)]
    tests = [{"item": f"{r['repo']}/{p}", "evidence": ev.format(lines=ls[:5])} for p, ls in files if is_test_path(p)]
    if not items:
        return "only test call sites"
    lab = {"id": qid, "items": items, "tests": tests, "completeness": "lower_bound", "match": "file",
           "note": f"{what} by {r['sha'][:12]}: the files whose call sites that change updated and that still call "
                   f"the symbol at HEAD. Callers it did not need to touch are missing, so recall only.",
           "change": {"repo": r["repo"], "sha": r["sha"], "parent": r["parent"], "title": r["title"]}}
    return q, lab


def clean_title(t):
    """A change or story title with ticket ids, conventional-commit prefixes and branch paths removed."""
    m = re.match(r"^Merged? (?:branch )?'([^']+)' into '[^']+'$", t)
    if m:
        t = m.group(1)
    # a branch name used as a title ("Feature/sc 123/add thing"): keep its last segment
    if re.match(r"^(feature|feat|bug|bugfix|hotfix|chore|fix|sc[ _-]?\d+)[ /]", t, re.I) and "/" in t:
        t = t.rsplit("/", 1)[-1]
    if " " not in t.strip():
        t = t.replace("-", " ").replace("_", " ")
    t = STORY.sub(" ", t)
    t = re.sub(r":[a-z0-9_+-]+:", " ", t)  # chat emoji codes
    t = re.sub(r"^\s*(feat|fix|chore|refactor|hotfix|bugfix)(\([^)]*\))?!?\s*:\s*", "", t, flags=re.I)
    t = re.sub(r"\[[^\]]*\]", " ", t)
    return re.sub(r"\s+", " ", t).strip(" -:;,./")


def usable_title(t):
    """The cleaned title, or None when it is too thin to ask about (fewer than four words of three letters or more,
    or a generic subject such as "WIP" or "Update file X")."""
    t = clean_title(t or "")
    if len(re.findall(r"[A-Za-z]{3,}", t)) < 4 or GENERIC.match(t):
        return None
    return t


