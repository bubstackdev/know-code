# Signals that put a file in a structural stratum's population. A file may be in several.
SIGNALS = {
    "di-implementations": ((), re.compile(r"\binterface\s+I[A-Z]\w*|\.Add(Scoped|Transient|Singleton)\b|"
                                                   r"\bRegisterType<|\bFor<\w+>\(\)\.Use")),
    "sql-table-access": (("sql",), re.compile(r"\bDbSet<|\bDbContext\b|\bSqlCommand\b|\bQuery(Async)?<|"
                                              r"\b(SELECT|INSERT\s+INTO|UPDATE|DELETE\s+FROM)\s+\w", re.I)),
    "bus-pub-sub": ((), re.compile(r"\bIConsumer<|\.Publish(<\w+>)?\(|\bIPublishEndpoint\b|\bISendEndpoint\b|"
                                   r"\bBasicPublish\b|\bBasicConsume\b")),
    "http-cross-repo": ((), re.compile(r"\[Http(Get|Post|Put|Delete|Patch)\b|\[Route\(|\bHttpClient\b|"
                                       r"\bthis\.http\.(get|post|put|delete|patch)\b|<cfhttp\b|\bcfhttp\(", re.I)),
}
PLAIN = {  # strata whose population is a whole category
    "cs-callers": "csharp", "angular-ui-flow": "angular", "cfml-callers": "cfml", "ansible-role-users": "ansible",
    "deploy-chain": "ci-deploy", "terraform-deps": "terraform",
}
SIGNAL_EXTRA = {"sql-table-access": {"csharp", "cfml"}, "bus-pub-sub": {"csharp", "cfml", "angular", "other-code"},
                "di-implementations": {"csharp"},
                "http-cross-repo": {"csharp", "cfml", "angular", "other-code"}}


def census(a):
    root, out = Path(a.root), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    cats = defaultdict(lambda: [0, 0])  # category -> [files, lines]
    strata = defaultdict(lambda: [0, 0])
    repo_lang, heads = {}, {}
    excluded = population(root, out)
    for d in repos_under(root):
        files = tracked(d)
        heads[d.name] = git(d, "rev-parse", "HEAD").strip()
        ans, ang = is_ansible_repo(files), is_angular_repo(files)
        per = Counter()
        for f in files:
            if skipped(f) or is_test_path(f):
                continue
            c = category(f, ans, ang)
            if c is None:
                continue
            text = read(d / f)
            n = text.count("\n") + 1 if text else 0
            per[c] += n
            if d.name in excluded or non_production(f) or generated_text(text):
                continue  # outside the structural population, but still counts toward the repo's language
            cats[c][0] += 1
            cats[c][1] += n
            for s, cat in PLAIN.items():
                if c == cat:
                    strata[s][0] += 1
                    strata[s][1] += n
            for s, (whole, rx) in SIGNALS.items():
                if c in whole or (c in SIGNAL_EXTRA[s] and rx.search(text)):
                    strata[s][0] += 1
                    strata[s][1] += n
        repo_lang[d.name] = per.most_common(1)[0][0] if per else "none"
    weights = stratum_weights(strata)
    res = {"categories": {k: {"files": v[0], "lines": v[1]} for k, v in sorted(cats.items())},
           "strata": {k: {"files": v[0], "lines": v[1]} for k, v in sorted(strata.items())},
           "weights": weights, "repo_language": repo_lang, "heads": heads, "excluded_repos": excluded}
    (out / "census.json").write_text(json.dumps(res, indent=1, sort_keys=True))
    for k, v in sorted(cats.items(), key=lambda kv: -kv[1][1]):
        print(f"  {k:14} {v[0]:7} files {v[1]:9} lines")
    for k, w in sorted(weights.items(), key=lambda kv: -kv[1]):
        print(f"  {k:20} {w:.3f}")


def stratum_weights(strata):
    """Each stratum's share: the mean of its share of files and its share of lines (lines alone would let a few huge
    files dominate, files alone would count a one-line config like a service)."""
    tf = sum(v[0] for v in strata.values()) or 1
    tl = sum(v[1] for v in strata.values()) or 1
    raw = {k: 0.5 * v[0] / tf + 0.5 * v[1] / tl for k, v in strata.items()}
    t = sum(raw.values()) or 1
    return {k: round(v / t, 4) for k, v in raw.items()}


def allocate(weights, n, minimum=1):
    """Largest-remainder allocation of n questions over the weights, each stratum getting at least `minimum`."""
    keys = sorted(weights)
    base = {k: minimum for k in keys}
    left = n - minimum * len(keys)
    if left < 0:
        raise ValueError("fewer questions than strata")
    t = sum(weights.values())
    exact = {k: left * weights[k] / t for k in keys}
    for k in keys:
        base[k] += int(exact[k])
    rem = n - sum(base.values())
    for k in sorted(keys, key=lambda k: (-(exact[k] - int(exact[k])), k))[:rem]:
        base[k] += 1
    return base


