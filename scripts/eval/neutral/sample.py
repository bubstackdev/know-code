CS_METHOD = re.compile(r"^\s*(?:(?:public|private|protected|internal|static|virtual|override|async|sealed|abstract|"
                       r"new|partial)\s+)+(?:[\w<>\[\],.?]+(?:\s*<[^()]*>)?)\s+(\w+)\s*(?:<[^>()]*>)?\s*\(", re.M)
FRAMEWORK_ENTRY = {"Main", "Dispose", "ToString", "Equals", "GetHashCode", "Configure", "ConfigureServices",
                   "OnModelCreating", "Up", "Down", "BuildTargetModel", "Consume", "Invoke", "InvokeAsync",
                   "OnActionExecuting", "OnActionExecuted", "OnException", "ExecuteAsync", "StartAsync", "StopAsync",
                   "Application_Start", "Page_Load", "InitializeComponent"}
CS_IFACE = re.compile(r"^\s*(?:public\s+|internal\s+)?(?:partial\s+)?interface\s+(I[A-Z]\w*)", re.M)
SQL_TABLE = re.compile(r"\bCREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?((?:[`\[\"]?\w+[`\]\"]?\.)?[`\[\"]?(\w+)[`\]\"]?)",
                       re.I)
USE_DB = re.compile(r"^\s*(?:USE|CREATE\s+DATABASE(?:\s+IF\s+NOT\s+EXISTS)?)\s+[`\[\"]?(\w+)", re.I | re.M)
# Directories holding copies of another server's schema (a warehouse, archive or backup replica).
REPLICA_DIR = re.compile(r"(^|/)[^/]*(warehouse|archive|backup|replica|copy|snapshot)[^/]*/", re.I)
EF_TABLE = re.compile(r"\[Table\(\s*\"(\w+)\"|\.ToTable\(\s*\"(\w+)\"")
# A file that talks to the message bus (MassTransit here): bus types or a consumer.
BUS_FILE = re.compile(r"\busing MassTransit\b|\bIPublishEndpoint\b|\bISendEndpoint\b|\bIBus\b|\bConsumeContext<|"
                      r"\bIConsumer<|\bIRequestClient<")
# Receivers of in-process dispatch (mediators, command senders), whose Send/Publish is not a bus message.
IN_PROCESS = re.compile(r"mediator|command|dispatcher|handler", re.I)
BUS_MSG = re.compile(r"\bIConsumer<\s*(\w+)\s*>|\.Publish(?:<\s*(\w+)\s*>|\(\s*new\s+(\w+)\b)|"
                     r"\.Send(?:<\s*(\w+)\s*>|\(\s*new\s+(\w+)\b)")
ROUTE_CLASS = re.compile(r"\[(?:Route|RoutePrefix)\(\s*@?\"([^\"]*)\"")
ROUTE_ACTION = re.compile(r"\[Http(Get|Post|Put|Delete|Patch)(?:\(\s*@?\"([^\"]*)\")?")
NG_COMPONENT = re.compile(r"@Component\s*\(\s*\{[^}]*?selector\s*:\s*['\"]([^'\"]+)['\"]", re.S)
JS_BLOCK = re.compile(r"<script\b[^>]*>.*?</script\s*>", re.I | re.S)
CFSCRIPT_BLOCK = re.compile(r"<cfscript\b[^>]*>.*?</cfscript\s*>", re.I | re.S)
CF_TAG_FUNC = re.compile(r"<cffunction\s+[^>]*?name\s*=\s*[\"'](\w+)[\"']", re.I)
CF_SCRIPT_FUNC = re.compile(r"(?:^|(?<=[;{}>]))\s*(?:public|private|remote|package)?\s*(?:[\w.]+\s+)?"
                            r"function\s+(\w+)\s*\(", re.I | re.M)
SCRIPT_COMPONENT = re.compile(r"^\s*(?:(?:/\*.*?\*/|//[^\n]*)\s*)*(?:import\s[^;]*;\s*)*component\b", re.I | re.S)


def cfml_functions(text, ext):
    """CFML functions a file declares, as (name, offset): `<cffunction>` tags, and script `function`s inside
    `<cfscript>` or in a script-syntax component. JavaScript `function`s in a page's `<script>` blocks are not CFML
    and are left out."""
    js = [m.span() for m in JS_BLOCK.finditer(text)]

    def in_js(pos):
        return any(a <= pos < b for a, b in js)

    out = [(m.group(1), m.start()) for m in CF_TAG_FUNC.finditer(text) if not in_js(m.start())]
    if ext == ".cfc" and SCRIPT_COMPONENT.match(text):
        script = [(0, len(text))]
    else:
        script = [m.span() for m in CFSCRIPT_BLOCK.finditer(text)]
    for a, b in script:
        for m in CF_SCRIPT_FUNC.finditer(text, a, b):
            if not in_js(m.start(1)):
                out.append((m.group(1), m.start(1)))
    return sorted(out, key=lambda x: x[1])


def table_family(name):
    """Date- or number-sharded tables (`log_20100514_7163`, `requests_2017_10`) collapse to one family, so a
    stratum drawn uniformly over families is not swamped by thousands of shards of one table."""
    return re.sub(r"(_\d+|\d{4,})+$", "", name.lower()) or name.lower()


TF_RESOURCE = re.compile(r"^\s*resource\s+\"([\w-]+)\"\s+\"([\w-]+)\"", re.M)


def structural_candidates(d, files, stratum, ansible_repo, angular_repo, *, eligible_files=None):
    """Every candidate subject of one stratum in one repo, as dicts with at least `key`, `file` and `line`.
    Generated, vendored, test and non-production files are not candidates by default.
    An explicit eligible_files set replaces these legacy file filters for separately reviewed populations."""
    out = []

    def read_src(path):  # generator output reads as empty, so it yields no candidates
        if eligible_files is not None:
            return Path(path).read_text(encoding="utf-8", errors="replace")
        text = read(path)
        return "" if generated_text(text) else text

    def lines_of(text, pos):
        return text.count("\n", 0, pos) + 1

    for f in files:
        if (f not in eligible_files if eligible_files is not None
                else skipped(f) or is_test_path(f) or non_production(f)):
            continue
        cat = category(f, ansible_repo, angular_repo)
        ext = os.path.splitext(f)[1].lower()
        if stratum == "cs-callers" and cat == "csharp" and not f.endswith("Controller.cs"):
            text = read_src(d / f)
            stem = os.path.basename(f)[:-3]
            for m in CS_METHOD.finditer(text):
                name = m.group(1)
                if name in KEYWORDS or name in FRAMEWORK_ENTRY or name == stem or " extern " in m.group(0):
                    continue
                out.append({"key": name, "file": f, "line": lines_of(text, m.start(1))})
        elif stratum == "di-implementations" and cat == "csharp":
            text = read_src(d / f)
            for m in CS_IFACE.finditer(text):
                out.append({"key": m.group(1), "file": f, "line": lines_of(text, m.start(1))})
        elif stratum == "sql-table-access" and cat in {"sql", "csharp"}:
            text = read_src(d / f)
            rx = SQL_TABLE if cat == "sql" else EF_TABLE
            uses = [(m.start(), m.group(1)) for m in USE_DB.finditer(text)] if cat == "sql" else []
            for m in rx.finditer(text):
                name = m.group(2) if cat == "sql" else (m.group(1) or m.group(2))
                if name.startswith("#") or name.lower().startswith(("tmp", "temp")):
                    continue
                if cat == "sql":
                    prior = [db for pos, db in uses if pos < m.start()]
                    qual = re.match(r"[`\[\"]?(\w+)[`\]\"]?\.", m.group(1))
                    stem = os.path.splitext(os.path.basename(f))[0]
                    # a numbered migration names a step, not a database: the repo's own database then
                    db = (qual.group(1) if qual else prior[-1] if prior
                          else d.name if re.match(r"\d", stem) else stem)
                else:
                    db = f"{d.name} (EF model)"
                fam = table_family(name)
                out.append({"key": f"{db.lower()}.{fam}", "family": fam, "name": name, "db": db, "file": f,
                            "replica": bool(REPLICA_DIR.search(f)), "line": lines_of(text, m.start())})
        elif stratum == "bus-pub-sub" and cat == "csharp":
            text = read_src(d / f)
            if not BUS_FILE.search(text):
                continue  # no message bus here: Send/Publish are a mediator's or a command sender's
            for m in BUS_MSG.finditer(text):
                name = next(g for g in m.groups() if g)
                if not m.group(0).startswith("I"):  # a Publish/Send call: whose?
                    line_start = text.rfind("\n", 0, m.start()) + 1
                    receiver = re.findall(r"[\w.]+$", text[line_start:m.start()].rstrip())
                    if receiver and IN_PROCESS.search(receiver[-1]):
                        continue
                out.append({"key": name, "file": f, "line": lines_of(text, m.start())})
        elif stratum == "http-cross-repo" and cat == "csharp" and f.endswith("Controller.cs"):
            # the endpoint is named by its action, not a computed route: routes come from base classes,
            # conventions and `nameof`, and resolving them is the labeller's job
            text = read_src(d / f)
            cls = os.path.basename(f)[:-len(".cs")]
            for m in ROUTE_ACTION.finditer(text):
                am = CS_METHOD.search(text, m.end())
                if not am:
                    continue
                out.append({"key": f"{m.group(1).upper()} {cls}.{am.group(1)}", "file": f,
                            "line": lines_of(text, am.start(1))})
        elif stratum == "angular-ui-flow" and cat == "angular" and f.endswith(".component.ts"):
            text = read_src(d / f)
            m = NG_COMPONENT.search(text)
            if m:
                out.append({"key": m.group(1), "file": f, "line": lines_of(text, m.start(1))})
        elif stratum == "cfml-callers" and ext in {".cfc", ".cfm", ".cfml"}:
            text = read_src(d / f)
            for name, pos in cfml_functions(text, ext):
                if name.lower() in {"init", "onapplicationstart", "onrequeststart", "onrequest", "onsessionstart",
                                    "onerror", "onmissingtemplate", "onrequestend", "onsessionend",
                                    "onapplicationend"}:
                    continue
                out.append({"key": name, "file": f, "line": lines_of(text, pos)})
        elif stratum == "ansible-role-users" and cat == "ansible":
            parts = f.split("/")
            if f == "tasks/main.yml":
                out.append({"key": d.name, "file": f, "line": 1, "role_repo": True})
            elif len(parts) >= 4 and parts[0] == "roles" and parts[2] == "tasks" and parts[3] == "main.yml":
                out.append({"key": parts[1], "file": f, "line": 1})
        elif stratum == "deploy-chain" and f == ".gitlab-ci.yml":
            text = read_src(d / f)
            if re.search(r"deploy", text, re.I):
                out.append({"key": d.name, "file": f, "line": 1})
        elif stratum == "terraform-deps" and ext == ".tf":
            text = read_src(d / f)
            for m in TF_RESOURCE.finditer(text):
                out.append({"key": f"{m.group(1)}.{m.group(2)}", "file": f, "line": lines_of(text, m.start(1))})
    return out


