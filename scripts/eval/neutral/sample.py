#!/usr/bin/env python3
"""Sampler for the neutral code-graph benchmark: draws questions from sources no tool under test has influenced.

    sample.py census     --root <clones> --out <dir>             corpus make-up and stratum weights
    sample.py history    --root <clones> --out <dir> [--seed N]  history questions (locate, co-change, impact) with
                                                                 their mechanical labels, and ticket candidates
    sample.py structural --root <clones> --out <dir> [--seed N]  random symbols per structural stratum (to be labelled
                                                                 by hand from source)
    sample.py assemble   --out <dir>                             joins everything into questions.jsonl, labels.jsonl
                                                                 and manifest.md, and validates the bank

Nothing here runs or reads the output of any code-graph tool: candidates come from `git` and file listings with
regular expressions. Every random draw goes through one `random.Random(seed)` per step, over lists sorted first, so
the same corpus at the same commits and the same seed give the same bank. Standard library only.
"""

