def _yaml_by_repo(root, ctx):
    """Lower-cased text of every YAML file per repo, built once."""
    if "yaml" not in ctx:
        ctx["yaml"] = {}
        for d in repos_under(root):
            ctx["yaml"][d.name] = "\n".join(read(d / f).lower() for f in tracked(d)
                                            if f.endswith((".yml", ".yaml")) and not skipped(f))
    return ctx["yaml"]


def complex_role(c, root, ctx, decls=None):
    """A role used from at least two other repos, or one that itself depends on other roles."""
    name = c["key"].lower()
    rx = re.compile(rf"(?<![\w.-]){re.escape(name)}(?![\w-])")
    users = sum(1 for r, text in _yaml_by_repo(root, ctx).items() if r.lower() != name and rx.search(text))
    meta = read(Path(root) / c["repo"] / c["file"].replace("tasks/main.yml", "meta/main.yml"))
    deps = re.search(r"^dependencies:\s*\n\s*-", meta, re.M)
    return users >= 2 or bool(deps)


def complex_pipeline(c, root, ctx, decls=None):
    """A pipeline that includes shared templates and hands off to a deploy tool: at least two hops."""
    text = read(Path(root) / c["repo"] / c["file"])
    return bool(re.search(r"^include:", text, re.M)) and bool(
        re.search(r"ansible-playbook|helm |terraform |kubectl |ssh |docker push|trigger:", text))


def complex_resource(c, root, ctx, decls=None):
    """A resource that references another address and is itself referenced from another block."""
    d = Path(root) / c["repo"]
    here = (d / c["file"]).parent
    texts = {f: read(here / f) for f in os.listdir(here) if f.endswith(".tf")}
    addr = c["key"]
    referenced = sum(len(re.findall(rf"\b{re.escape(addr)}\.", t)) for t in texts.values())
    body = texts.get(os.path.basename(c["file"]), "").splitlines()[c["line"] - 1:]
    block, depth = [], 0
    for ln in body:
        block.append(ln)
        depth += ln.count("{") - ln.count("}")
        if depth <= 0 and len(block) > 1:
            break
    refs = re.findall(r"\b(?:var|local|module|data\.\w+|aws_\w+|azurerm_\w+|google_\w+|random_\w+|gitlab_\w+|"
                      r"vault_\w+)\.\w+", "\n".join(block[1:]))
    return referenced >= 1 and len(refs) >= 1


CALL_TOKEN = re.compile(r"\b([A-Za-z_]\w*)\s*(?:<[^<>()]*>)?\s*\(")


def _cs_calls(root, ctx):
    """Per repo, how often each name appears followed by `(` in C# source (calls plus declarations), built once."""
    if "cs" not in ctx:
        ctx["cs"] = {}
        for d in repos_under(root):
            cnt = Counter()
            for f in tracked(d):
                if f.endswith(".cs") and not skipped(f):
                    cnt.update(CALL_TOKEN.findall(read(d / f)))
            ctx["cs"][d.name] = cnt
    return ctx["cs"]


def hard_method(c, root, ctx, decls):
    """A method with overloads in its file, more than 10 likely call sites, or likely callers in another repo. Call
    sites are grep counts of `Name(` less the name's declarations, so a common name shared by unrelated methods
    counts too: the filter is a proxy and the label decides what is true."""
    if c.get("overloads", 1) > 1:
        return True
    name, calls = c["key"], _cs_calls(root, ctx)
    here = calls.get(c["repo"], Counter())[name] - decls[(c["repo"], name)]
    elsewhere = sum(cnt[name] - decls[(r, name)] for r, cnt in calls.items() if r != c["repo"] and cnt[name])
    return here + max(elsewhere, 0) > 10 or elsewhere > 0


def _cf_texts(root, ctx, repo):
    """Every CFML file of a repo, as {path: text}, built once per repo."""
    cache = ctx.setdefault("cf", {})
    if repo not in cache:
        d = Path(root) / repo
        cache[repo] = {f: read(d / f) for f in tracked(d)
                       if f.lower().endswith((".cfm", ".cfc", ".cfml")) and not skipped(f)}
    return cache[repo]


def hard_cf_function(c, root, ctx, decls):
    """A CFML function called from a file other than the one declaring it (reached through cfinclude or a
    component), by a grep for `name(`."""
    rx = re.compile(rf"(?<![\w.]){re.escape(c['key'])}\s*\(|\.{re.escape(c['key'])}\s*\(", re.I)
    return any(f != c["file"] and rx.search(t) for f, t in _cf_texts(root, ctx, c["repo"]).items())


