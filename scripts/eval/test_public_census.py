"""Synthetic source-only census checks; no network, source execution, indexing or models."""
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import unittest


SPEC=importlib.util.spec_from_file_location('public_census',Path(__file__).resolve().parents[1]/'census-public-eval.py')
census=importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(census)


class PublicCensusTests(unittest.TestCase):
    def fixture(self,base):
        source=base/'source'
        root=source/'view'/'example-client'
        (root/'libs/core').mkdir(parents=True)
        file=root/'libs/core/api.ts'
        data=b'export class ApiClient {}\n'
        file.write_bytes(data);file.chmod(0o444)
        metadata={'name':'example-client','commit':'a'*40,'url':'https://github.com/example/client.git','exclude':[]}
        manifest=base/'manifest.json'
        manifest.write_text(json.dumps({'format':1,'families':[{'name':'example','repos':[metadata]}]}))
        item={'path':'libs/core/api.ts','sha256':hashlib.sha256(data).hexdigest(),'bytes':len(data),'symlink':False}
        receipt={'manifest_sha256':hashlib.sha256(manifest.read_bytes()).hexdigest(),'stage':'source-ready; questions pending',
                 'repos':[dict(metadata,family='example',files=[item],excluded_paths=[],git_export_omissions=[])]}
        (source/'source-receipt.json').write_text(json.dumps(receipt))
        return manifest,source,file

    def test_primary_libs_are_retained_and_every_file_has_a_hash(self):
        with tempfile.TemporaryDirectory() as temp:
            base=Path(temp);manifest,source,_=self.fixture(base)
            result=census.census(manifest,source,base/'out')
            self.assertEqual(result['files'],1)
            self.assertFalse(result['automatic_exclusions'])
            rows=[json.loads(s) for s in (base/'out/files.jsonl').read_text().splitlines()]
            self.assertEqual(rows[0]['path'],'libs/core/api.ts')
            self.assertEqual(rows[0]['language'],'typescript')
            self.assertFalse(rows[0]['review_flags'])
            with self.assertRaisesRegex(ValueError,'existing evidence'):
                census.census(manifest,source,base/'out')

    def test_changed_writable_untracked_and_history_entries_are_rejected(self):
        with tempfile.TemporaryDirectory() as temp:
            base=Path(temp);manifest,source,file=self.fixture(base)
            file.chmod(0o644)
            with self.assertRaisesRegex(ValueError,'writable'):
                census.census(manifest,source,base/'out')
            file.write_bytes(b'export class Changed {}\n');file.chmod(0o444)
            with self.assertRaisesRegex(ValueError,'pinned receipt'):
                census.census(manifest,source,base/'out')
            (file.parent/'extra.ts').write_text('extra')
            with self.assertRaisesRegex(ValueError,'entry set'):
                census.census(manifest,source,base/'out')
            (file.parents[1]/'.git').mkdir()
            with self.assertRaisesRegex(ValueError,'history-containing'):
                census.census(manifest,source,base/'out')

    def test_review_flags_annotate_without_removing_sources(self):
        self.assertEqual(census.flags('libs/core/api.spec.ts',b''),['test-path'])
        self.assertEqual(census.flags('packages/core/Api.g.cs',b'// <auto-generated>'),['generated-filename','generated-header'])
        self.assertEqual(census.flags('third_party/client.ts',b''),['dependency-or-vendor-path'])
        self.assertEqual(census.flags('libs/core/api.ts',b''),[])

    def test_receipt_cannot_authorize_unreviewed_nested_privacy_metadata(self):
        with tempfile.TemporaryDirectory() as temp:
            base=Path(temp);manifest,source,_=self.fixture(base)
            receipt_path=source/'source-receipt.json'
            receipt=json.loads(receipt_path.read_text())
            receipt['repos'][0]['files'].append({'path':'libs/.knowcode-privacy.yml','bytes':0,'sha256':'0'*64,'symlink':False})
            receipt_path.write_text(json.dumps(receipt))
            with self.assertRaisesRegex(ValueError,'privacy metadata'):
                census.census(manifest,source,base/'out')
