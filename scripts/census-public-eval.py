#!/usr/bin/env python3
"""Verify pinned public source views and enumerate files before selecting evaluation questions.

No source execution, builds, dependency installs, model calls, Git indexing or KnowCode queries.
Flags describe files for scope review; they never remove files from the exported source population.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import stat


ROOT = Path(__file__).resolve().parent.parent
LANGUAGES = {'.cs':'csharp', '.ts':'typescript', '.tsx':'typescript', '.js':'javascript', '.jsx':'javascript',
             '.mjs':'javascript', '.cjs':'javascript', '.html':'html', '.sql':'sql', '.py':'python',
             '.rs':'rust', '.swift':'swift', '.tf':'terraform', '.yml':'yaml', '.yaml':'yaml'}
TEST_PARTS = {'test','tests','__tests__','specs','__mocks__','fixtures','testdata'}
DEMO_PARTS = {'example','examples','sample','samples','demo','demos','benchmark','benchmarks'}
DEPENDENCY_PARTS = {'node_modules','vendor','third_party','third-party','bower_components'}
BUILD_PARTS = {'obj','dist','target','.angular','coverage','.next'}
GENERATED = re.compile(r'<auto-?generated|This code was generated by a tool|@generated\b|Code generated .* DO NOT EDIT',re.I)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def flags(path: str, data: bytes) -> list[str]:
    """Conservative review annotations, not an exclusion or a claim of source completeness."""
    file = PurePosixPath(path)
    directories = {part.casefold() for part in file.parts[:-1]}
    name = file.name.casefold()
    found = []
    if directories & TEST_PARTS or re.search(r'(?:\.spec|\.test)\.[^.]+$|tests?\.cs$',name):
        found.append('test-path')
    if directories & DEMO_PARTS:
        found.append('sample-or-benchmark-path')
    if directories & DEPENDENCY_PARTS:
        found.append('dependency-or-vendor-path')
    if directories & BUILD_PARTS:
        found.append('build-or-output-path')
    if re.search(r'\.g(?:\.i)?\.cs$|\.designer\.cs$|\.min\.js$|\.d\.ts$',name):
        found.append('generated-filename')
    if file.suffix.casefold() in LANGUAGES and GENERATED.search(data[:2048].decode('utf-8',errors='replace')):
        found.append('generated-header')
    return found


def safe_relative(value: str) -> PurePosixPath:
    path=PurePosixPath(value)
    if not value or path.is_absolute() or '..' in path.parts or '\\' in value or any(p.casefold()=='.git' for p in path.parts):
        raise ValueError('unsafe or history-containing source path')
    return path


# A privacy file (KnowCode's, or a code base's own under its own name): any dotfile naming privacy, in YAML or TOML.
PRIVACY_FILE=re.compile(r'^\.[\w.-]*privacy[\w.-]*\.(?:ya?ml|toml)$', re.I)


def inspect_view(root: Path, repo: dict) -> list[dict]:
    if root.is_symlink() or not root.is_dir():
        raise ValueError('source view is not a real directory')
    expected={}
    for item in repo['files']:
        name=safe_relative(item['path']).as_posix()
        if PRIVACY_FILE.match(PurePosixPath(name).name):
            raise ValueError('unhandled source privacy metadata; resolve scope before census')
        if name in expected:
            raise ValueError('duplicate source receipt path')
        expected[name]=item
    if not expected:
        raise ValueError('empty source receipt')

    def entries() -> set[str]:
        paths=set()
        def fail(error):
            raise error
        for directory, children, files in os.walk(root,followlinks=False,onerror=fail):
            for name in children+files:
                path=Path(directory)/name
                relative=path.relative_to(root).as_posix()
                safe_relative(relative)
                mode=path.lstat().st_mode
                if not stat.S_ISDIR(mode):
                    paths.add(relative)
        return paths

    def read(name: str, expected_item: dict) -> bytes:
        path=root/name
        # Reject an ancestor replaced with a symlink, even when it resolves inside the view.
        parent=root
        for part in PurePosixPath(name).parts[:-1]:
            parent=parent/part
            if parent.is_symlink():
                raise ValueError('symlinked source ancestor')
        before=path.lstat()
        link=stat.S_ISLNK(before.st_mode)
        if link!=expected_item['symlink']:
            raise ValueError('source entry type differs from receipt')
        if link:
            if not path.resolve(strict=True).is_relative_to(root.resolve()):
                raise ValueError('source symlink escapes view')
            data=os.fsencode(os.readlink(path))
        elif stat.S_ISREG(before.st_mode):
            if before.st_mode & 0o222:
                raise ValueError('source file is writable; use the prepared immutable view')
            data=path.read_bytes()
        else:
            raise ValueError('nonregular source entry')
        after=path.lstat()
        if (before.st_ino,before.st_size,before.st_mtime_ns)!=(after.st_ino,after.st_size,after.st_mtime_ns):
            raise ValueError('source changed during census')
        if len(data)!=expected_item['bytes'] or digest(data)!=expected_item['sha256']:
            raise ValueError('source bytes differ from pinned receipt')
        return data

    if entries()!=set(expected):
        raise ValueError('source entry set differs from pinned receipt')
    rows=[]
    for name,item in sorted(expected.items()):
        data=read(name,item)
        language=LANGUAGES.get(PurePosixPath(name).suffix.casefold()) if not item['symlink'] else None
        rows.append({'repo':repo['name'],'family':repo['family'],'path':name,'sha256':item['sha256'],
                     'bytes':item['bytes'],'symlink':item['symlink'],'language':language,
                     'review_flags':flags(name,data) if not item['symlink'] else ['symlink']})
    # Recheck after all reads; a census must not silently combine two different source states.
    if entries()!=set(expected):
        raise ValueError('source entries changed during census')
    for name,item in sorted(expected.items()):
        read(name,item)
    return rows


def census(manifest_path: Path, source_root: Path, destination: Path) -> dict:
    manifest_bytes=manifest_path.read_bytes()
    manifest=json.loads(manifest_bytes)
    receipt_bytes=(source_root/'source-receipt.json').read_bytes()
    receipt=json.loads(receipt_bytes)
    if manifest.get('format')!=1 or receipt.get('manifest_sha256')!=digest(manifest_bytes):
        raise ValueError('manifest differs from prepared source receipt')
    if not receipt.get('stage','').startswith('source-ready;'):
        raise ValueError('public source preparation is incomplete')
    expected={}
    for family in manifest['families']:
        for repo in family['repos']:
            name=repo['name']
            if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._-]*',name) or name in expected:
                raise ValueError('invalid or duplicate repository name')
            expected[name]=dict(repo,family=family['name'])
    if len(receipt['repos'])!=len(expected) or {r['name'] for r in receipt['repos']}!=set(expected):
        raise ValueError('repository set differs from manifest')
    view=source_root/'view'
    if view.is_symlink() or not view.is_dir() or {p.name for p in view.iterdir()}!=set(expected):
        raise ValueError('source view repository entries differ from manifest')
    destination=destination.resolve()
    if destination.is_relative_to(ROOT) or destination.is_relative_to(source_root.resolve()):
        raise ValueError('census output must be outside source and prepared views')
    if destination.exists() and any(destination.iterdir()):
        raise ValueError('output must be new or empty; existing evidence is retained')
    rows=[]
    summaries=[]
    for repo in sorted(receipt['repos'],key=lambda item:item['name']):
        if any(repo.get(k)!=v for k,v in expected[repo['name']].items()):
            raise ValueError('source repository metadata differs from manifest')
        files=inspect_view(view/repo['name'],repo)
        rows.extend(files)
        summaries.append({'name':repo['name'],'family':repo['family'],'commit':repo['commit'],
                          'files':len(files),'languages':dict(sorted(Counter(r['language'] or 'non-code' for r in files).items())),
                          'review_flags':dict(sorted(Counter(flag for r in files for flag in r['review_flags']).items())),
                          'explicit_excluded_paths':repo['excluded_paths'],'git_export_omissions':repo['git_export_omissions']})
    output=''.join(json.dumps(row,sort_keys=True)+'\n' for row in rows)
    result={'format':1,'stage':'file census; scope review and question sampling pending; no scored runs',
            'manifest_sha256':digest(manifest_bytes),'source_receipt_sha256':digest(receipt_bytes),
            'tool_sha256':digest(Path(__file__).read_bytes()),'files_sha256':digest(output.encode()),
            'repos':summaries,'files':len(rows),'automatic_exclusions':[],
            'scope_policy':'Every exported file is retained. Review flags annotate possible test/generated/vendor/build sources; they are not exclusions. lib, libs and packages are not excluded by directory name.'}
    destination.mkdir(parents=True,exist_ok=True,mode=0o700)
    (destination/'files.jsonl').write_text(output)
    (destination/'census.json').write_text(json.dumps(result,indent=2)+'\n')
    return result


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest',type=Path,default=ROOT/'eval/public-v1/manifest.json')
    parser.add_argument('--source',type=Path,required=True)
    parser.add_argument('--out',type=Path,required=True)
    args=parser.parse_args()
    result=census(args.manifest,args.source.resolve(strict=True),args.out)
    print(json.dumps({'repos':len(result['repos']),'files':result['files'],'questions_sampled':False,'scored_runs':0}))
